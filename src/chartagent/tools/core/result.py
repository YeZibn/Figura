"""Typed tool results with bounded, in-memory visual observations."""

from __future__ import annotations

import json
import math
from dataclasses import dataclass, field
from collections.abc import Mapping
from typing import Any, Iterable

SUPPORTED_GENERATED_IMAGE_MIME_TYPES = frozenset(
    {"image/png", "image/jpeg", "image/webp"}
)
DEFAULT_MAX_GENERATED_IMAGE_BYTES = 10 * 1024 * 1024
DEFAULT_MAX_GENERATED_IMAGES = 4
DEFAULT_MAX_DASHBOARD_IMAGES = 16
_EVIDENCE_TYPES = {
    "extract_text": "text",
    "decompose_chart_image": "layout",
    "inspect_chart_layout": "layout",
    "measure_bars": "geometry",
    "extract_line_series": "geometry",
    "extract_pie_slices": "geometry",
    "extract_scatter_points": "geometry",
}
_EVIDENCE_REFERENCE_KEYS = (
    "panels",
    "proposals",
    "crops",
    "ocr",
    "frame",
    "plot_frame",
    "plot_area",
    "axes",
    "baseline",
    "bars",
    "series",
    "points",
    "sectors",
    "layout_context",
)


@dataclass(frozen=True)
class GeneratedImage:
    """One model-facing image generated by a tool.

    ``content`` is intentionally bytes rather than a local path. This keeps the
    attachment boundary explicit and prevents tools from exposing arbitrary
    workspace files to the remote model.
    """

    content: bytes
    media_type: str
    caption: str
    metadata: Mapping[str, Any] = field(default_factory=dict)


@dataclass(frozen=True)
class ToolResult:
    """Structured tool data plus optional visual evidence and warnings."""

    data: Any
    images: tuple[GeneratedImage, ...] = field(default_factory=tuple)
    warnings: tuple[str, ...] = field(default_factory=tuple)
    evidence: Mapping[str, Any] | None = None

    def __post_init__(self) -> None:
        object.__setattr__(self, "images", tuple(self.images))
        object.__setattr__(self, "warnings", tuple(self.warnings))


def build_evidence_summary(
    *,
    source_tool: str,
    source_attachment_id: str | None,
    data: Any,
    warnings: Iterable[object],
    images: Iterable[GeneratedImage],
) -> dict[str, Any]:
    """Build a bounded, source-attributable summary for chart observations."""
    evidence_type = _EVIDENCE_TYPES.get(source_tool, "tool")
    confidence_value = data.get("confidence") if isinstance(data, Mapping) else None
    if isinstance(confidence_value, Mapping):
        confidence = {
            str(key)[:48]: _bounded_confidence(value)
            for key, value in list(confidence_value.items())[:8]
            if isinstance(key, str) and _bounded_confidence(value) is not None
        }
    else:
        parsed_confidence = _bounded_confidence(confidence_value)
        confidence = {"overall": parsed_confidence} if parsed_confidence is not None else {}

    normalized_warnings = [
        item[:160]
        for item in warnings
        if isinstance(item, str)
    ][:12]
    conflicts: list[Any] = []
    if isinstance(data, Mapping):
        direct_conflicts = data.get("conflicts")
        nested_evidence = data.get("evidence")
        nested_conflicts = (
            nested_evidence.get("conflicts")
            if isinstance(nested_evidence, Mapping)
            else None
        )
        comparison = data.get("layout_comparison")
        comparison_conflicts = (
            comparison.get("conflicts")
            if isinstance(comparison, Mapping)
            else None
        )
        for candidate in (direct_conflicts, nested_conflicts, comparison_conflicts):
            if isinstance(candidate, (list, tuple)):
                conflicts.extend(candidate)
    normalized_conflicts: list[Any] = []
    for conflict in conflicts:
        if isinstance(conflict, Mapping):
            item: dict[str, Any] = {}
            field = conflict.get("field")
            sources = conflict.get("sources")
            message = conflict.get("message")
            if isinstance(field, str):
                item["field"] = field[:80]
            if isinstance(sources, (list, tuple)):
                item["sources"] = [str(source)[:64] for source in sources[:6]]
            if isinstance(message, str):
                item["message"] = message[:160]
            if item:
                normalized_conflicts.append(item)
        elif isinstance(conflict, str):
            normalized_conflicts.append(conflict[:160])
        if len(normalized_conflicts) >= 8:
            break
    references: list[dict[str, str]] = []
    if isinstance(source_attachment_id, str) and source_attachment_id:
        references.append({"scope": "source_image", "attachment_id": source_attachment_id[:160]})
        if isinstance(data, Mapping):
            for key in _EVIDENCE_REFERENCE_KEYS:
                if key in data:
                    references.append({"scope": key, "attachment_id": source_attachment_id[:160]})

    image_list = list(images)
    return {
        "evidence_type": evidence_type,
        "source_tool": source_tool[:80],
        "source_attachment_id": source_attachment_id[:160] if isinstance(source_attachment_id, str) else None,
        "confidence": confidence,
        "warnings": normalized_warnings,
        "conflicts": normalized_conflicts,
        "source_image_refs": references[:12],
        "visual_observations": {
            "count": len(image_list),
            "captions": [image.caption[:160] for image in image_list[:4]],
        },
    }


def _bounded_confidence(value: object) -> float | None:
    try:
        parsed = float(value)
    except (TypeError, ValueError):
        return None
    if not math.isfinite(parsed):
        return None
    return max(0.0, min(1.0, parsed))


@dataclass(frozen=True)
class DispatchedObservation:
    """JSON content plus validated image bytes for the Agent transport."""

    content: str
    images: tuple[GeneratedImage, ...] = field(default_factory=tuple)


def normalize_tool_result(
    result: Any,
    *,
    max_image_bytes: int = DEFAULT_MAX_GENERATED_IMAGE_BYTES,
    max_images: int = DEFAULT_MAX_GENERATED_IMAGES,
    source_tool: str | None = None,
    source_attachment_id: str | None = None,
    source_panel_id: str | None = None,
    source_run_id: str | None = None,
    source_parent_attempt_id: str | None = None,
    source_measurement_target: Mapping[str, Any] | None = None,
) -> DispatchedObservation:
    """Normalize a legacy value or enriched ``ToolResult``.

    Legacy values retain their old JSON representation. Invalid generated
    images become warnings while valid structured data and sibling images are
    preserved. Serialization errors are intentionally left to the dispatch
    boundary, which turns them into structured tool errors.
    """
    if not isinstance(result, ToolResult):
        if (
            source_tool in {
                "measure_bars",
                "extract_line_series",
                "extract_pie_slices",
                "extract_scatter_points",
            }
            and isinstance(result, Mapping)
            and "error" not in result
        ):
            from ...measurement import attach_measurement_quality

            legacy_data = attach_measurement_quality(
                result,
                source_tool=source_tool,
                image_count=0,
                source_attachment_id=source_attachment_id,
                source_panel_id=source_panel_id or _panel_id_from_data(result),
                source_run_id=source_run_id,
                parent_attempt_id=source_parent_attempt_id,
                measurement_target=source_measurement_target,
            )
            return DispatchedObservation(
                json.dumps(
                    {
                        "data": legacy_data,
                        "warnings": ["legacy measurement result was downgraded to provisional"],
                        "images": [],
                    },
                    ensure_ascii=False,
                )
            )
        return DispatchedObservation(json.dumps(result, ensure_ascii=False))

    warnings = _normalize_warnings(result.warnings)
    images: list[GeneratedImage] = []
    metadata: list[dict[str, Any]] = []

    for index, candidate in enumerate(result.images):
        if index >= max_images:
            warnings.append(
                f"generated image {index + 1} omitted: image count exceeds limit {max_images}"
            )
            continue
        warning = _image_warning(candidate, max_image_bytes=max_image_bytes)
        if warning is not None:
            warnings.append(f"generated image {index + 1} omitted: {warning}")
            continue
        images.append(candidate)
        image_metadata: dict[str, Any] = {
            "media_type": candidate.media_type.lower(),
            "caption": candidate.caption,
            "attached": True,
        }
        if isinstance(candidate.metadata, Mapping):
            for key, value in candidate.metadata.items():
                if not isinstance(key, str) or len(key) > 64:
                    continue
                if isinstance(value, (str, int, float, bool)) or value is None:
                    image_metadata[key] = value
        metadata.append(image_metadata)

    data_payload = result.data
    resolved_measurement_target = source_measurement_target
    if resolved_measurement_target is None and isinstance(result.data, Mapping):
        candidate_target = result.data.get("measurement_target")
        if isinstance(candidate_target, Mapping):
            resolved_measurement_target = candidate_target
    if source_tool in {
        "measure_bars",
        "extract_line_series",
        "extract_pie_slices",
        "extract_scatter_points",
    } and isinstance(result.data, Mapping):
        # Keep the sensor payload intact and add only a bounded, code-owned
        # quality envelope at the transport boundary.  The lazy import avoids
        # coupling the low-level result primitive to chart sensor modules.
        from ...measurement import attach_measurement_quality

        data_payload = attach_measurement_quality(
            result.data,
            source_tool=source_tool,
            warnings=warnings,
            image_count=len(images),
            source_attachment_id=source_attachment_id,
            source_panel_id=source_panel_id or _panel_id_from_data(result.data),
            source_run_id=source_run_id,
            parent_attempt_id=source_parent_attempt_id,
            measurement_target=resolved_measurement_target,
            captions=[image.caption for image in images],
        )

    payload: dict[str, Any] = {
        "data": data_payload,
        "warnings": warnings,
        "images": metadata,
    }
    evidence = result.evidence
    if evidence is None and source_tool in _EVIDENCE_TYPES:
        evidence = build_evidence_summary(
            source_tool=source_tool,
            source_attachment_id=source_attachment_id,
            data=data_payload,
            warnings=warnings,
            images=images,
        )
    if evidence is not None:
        payload["evidence"] = dict(evidence)
    content = json.dumps(payload, ensure_ascii=False)
    return DispatchedObservation(content=content, images=tuple(images))


def _panel_id_from_data(data: Mapping[str, Any]) -> str | None:
    scope = data.get("scope")
    if isinstance(scope, Mapping):
        value = scope.get("panel_id")
        if isinstance(value, str) and value.strip():
            return value
    measurement = data.get("measurement")
    if isinstance(measurement, Mapping):
        source = measurement.get("source")
        if isinstance(source, Mapping) and isinstance(source.get("panel_id"), str):
            return source["panel_id"]
    return None


def _normalize_warnings(warnings: Iterable[object]) -> list[str]:
    normalized: list[str] = []
    for warning in warnings:
        if isinstance(warning, str):
            normalized.append(warning)
        else:
            normalized.append(f"invalid non-string warning ignored: {warning!r}")
    return normalized


def _image_warning(candidate: object, *, max_image_bytes: int) -> str | None:
    if not isinstance(candidate, GeneratedImage):
        return "expected a GeneratedImage payload, not a path or arbitrary value"
    if not isinstance(candidate.content, bytes):
        return "content must be immutable bytes"
    if not candidate.content:
        return "content is empty"
    media_type = candidate.media_type.lower() if isinstance(candidate.media_type, str) else ""
    if media_type not in SUPPORTED_GENERATED_IMAGE_MIME_TYPES:
        return f"unsupported media type {candidate.media_type!r}"
    if len(candidate.content) > max_image_bytes:
        return (
            f"payload size {len(candidate.content)} exceeds "
            f"the {max_image_bytes}-byte limit"
        )
    if not isinstance(candidate.caption, str) or not candidate.caption.strip():
        return "caption must be a non-empty string"
    return None


